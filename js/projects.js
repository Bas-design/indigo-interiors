/* =============================================================
   Indigo Interiors — projects.js
   Loads project data from assets/projects/ and renders:
   - the gallery grid + filter bar (gallery.html)
   - the featured strip on the home page (index.html)
   - a single project page (project.html?p=<folder-name>)
   Projects are plain folders: photos + one project.json each.
   See assets/projects/HOW-TO-ADD-A-PROJECT.md for the workflow.

   Data source: fetch() of the JSON files. When the site is opened
   from the file system (file://), fetch is blocked, so we fall back
   to the embedded snapshot in assets/projects/projects-data.js
   (window.INDIGO_PROJECTS, regenerated by rebuild-preview-data.js).
   ============================================================= */
(function () {
  'use strict';

  /* Generated project pages live two levels down at /projects/<slug>/
     and set INDIGO_BASE_PREFIX to '../../' before this script runs. The
     root-level pages never define it, so they get '' and nothing about
     them changes. Relative rather than root-relative throughout, so the
     site still works opened straight from disk. */
  var PREFIX = window.INDIGO_BASE_PREFIX || '';
  var BASE = PREFIX + 'assets/projects/';

  function fetchJSON(url) {
    return fetch(url, { cache: 'no-cache' }).then(function (r) {
      if (!r.ok) throw new Error(url + ' → HTTP ' + r.status);
      return r.json();
    });
  }

  function snapshot() {
    var s = window.INDIGO_PROJECTS;
    if (!s || !s.order) return null;
    return s.order.map(function (slug) {
      var p = s.data[slug];
      if (p) { p.slug = slug; return p; }
      return null;
    }).filter(Boolean);
  }

  /* Load the folder list, then every project.json. A broken project.json
     skips that one project (with a console warning) instead of blanking
     the page. Falls back to the embedded snapshot if fetch fails. */
  function loadAll() {
    return fetchJSON(BASE + 'projects.json').then(function (list) {
      var slugs = (list && list.projects) || [];
      return Promise.all(slugs.map(function (slug) {
        return fetchJSON(BASE + slug + '/project.json')
          .then(function (p) { p.slug = slug; return p; })
          .catch(function (err) {
            console.warn('[projects] skipping "' + slug + '":', err.message);
            return null;
          });
      }));
    }).then(function (projects) {
      return projects.filter(Boolean);
    }).catch(function (err) {
      var snap = snapshot();
      if (snap) {
        console.warn('[projects] fetch unavailable (' + err.message + ') — using embedded snapshot');
        return snap;
      }
      throw err;
    });
  }

  function loadOne(slug) {
    return fetchJSON(BASE + slug + '/project.json').then(function (p) {
      p.slug = slug;
      return p;
    }).catch(function (err) {
      var s = window.INDIGO_PROJECTS;
      if (s && s.data && s.data[slug]) {
        var p = s.data[slug];
        p.slug = slug;
        return p;
      }
      throw err;
    });
  }

  function el(tag, className, html) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    if (html !== undefined) node.innerHTML = html;
    return node;
  }

  function text(tag, className, value) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    node.textContent = value;
    return node;
  }

  function tile(p, delay) {
    var item = el('a', 'gallery-item');
    item.href = PREFIX + 'projects/' + encodeURIComponent(p.slug) + '/';
    item.dataset.category = p.category || '';
    item.style.setProperty('--d', delay + 's');

    var ph = el('div', 'ph');
    var img = el('img', 'ph__photo');
    img.src = BASE + p.slug + '/' + p.cover;
    img.alt = p.title;
    img.loading = 'lazy';
    ph.appendChild(img);

    var label = el('div', 'gallery-item__label');
    label.appendChild(text('strong', null, p.title));
    label.appendChild(text('span', null, p.categoryLabel || ''));

    item.appendChild(ph);
    item.appendChild(label);
    return item;
  }

  /* ---------- Gallery grid + filters (gallery.html) ---------- */
  function renderGrid(grid, projects) {
    grid.innerHTML = '';
    // real tiles now define the height; drop the reserved minimum
    grid.style.removeProperty('--rows');
    grid.style.minHeight = '0';
    projects.forEach(function (p, i) {
      var item = tile(p, i * 0.08);
      item.setAttribute('data-reveal', '');
      grid.appendChild(item);
      /* the IntersectionObserver in main.js ran before these existed,
         so reveal them directly */
      item.classList.add('in-view');
    });
  }

  /* ---------- Featured strip (index.html) ---------- */
  function renderFeatured(strip, projects) {
    var max = parseInt(strip.getAttribute('data-projects-featured'), 10) || 3;
    strip.innerHTML = '';
    strip.style.removeProperty('--rows');
    strip.style.minHeight = '0';
    projects.slice(0, max).forEach(function (p, i) {
      var item = tile(p, i * 0.12);
      item.setAttribute('data-reveal', '');
      strip.appendChild(item);
    });
    /* re-observe: on the home page these tiles are usually below the fold,
       so hook them into the scroll-reveal observer main.js exposes */
    if (window.INDIGO_OBSERVE) {
      strip.querySelectorAll('[data-reveal]').forEach(window.INDIGO_OBSERVE);
    } else {
      strip.querySelectorAll('[data-reveal]').forEach(function (n) {
        n.classList.add('in-view');
      });
    }
  }

  /* ---------- Project page (project.html) ---------- */
  function renderProject(root, p) {
    document.title = p.title + ' — Indigo Interiors';
    /* SEO: per-project description + canonical (Google renders JS pages,
       so these are picked up on the second-wave index) */
    var desc = document.querySelector('meta[name="description"]');
    if (desc && p.summary) desc.setAttribute('content', p.summary);
    /* On a generated page the canonical is already correct and baked
       in, so leave it alone. On the legacy project.html?p=<slug> URL,
       point it at the generated page — that is the real address, and
       without this every project claimed /project.html as its
       canonical and invited Google to collapse them into one. */
    if (!window.INDIGO_PROJECT_SLUG) {
      var canon = document.querySelector('link[rel="canonical"]');
      if (canon) {
        canon.setAttribute('href',
          'https://indigointeriors.com.au/projects/' + encodeURIComponent(p.slug) + '/');
      }
    }

    var head = el('section', 'page-hero');
    var headWrap = el('div', 'container');
    var back = el('a', 'project-back-top');
    back.href = PREFIX + 'gallery.html';
    back.setAttribute('aria-label', 'Back to gallery');
    back.innerHTML =
      '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="1.6">' +
      '<path d="M15 4 L7 12 L15 20"/></svg><span>Gallery</span>';
    headWrap.appendChild(back);
    headWrap.appendChild(text('p', 'eyebrow', (p.categoryLabel || 'Project') +
      (p.location ? ' · ' + p.location : '') + (p.year ? ' · ' + p.year : '')));
    headWrap.appendChild(text('h1', null, p.title));
    headWrap.appendChild(el('hr', 'rule rule--center'));
    if (p.summary) headWrap.appendChild(text('p', 'lede', p.summary));
    head.appendChild(headWrap);
    root.appendChild(head);

    if (p.brief && p.brief.length) {
      var briefSec = el('section', 'project-brief');
      var briefWrap = el('div', 'container--narrow');
      p.brief.forEach(function (para) {
        briefWrap.appendChild(text('p', null, para));
      });
      briefSec.appendChild(briefWrap);
      root.appendChild(briefSec);
    }

    var photosSec = el('section', 'section project-photos');
    var photosWrap = el('div', 'container');
    (p.photos || []).forEach(function (ph) {
      var row = el('article', 'project-row');

      var media = el('div', 'project-row__media');
      var img = el('img', null);
      img.src = BASE + p.slug + '/' + ph.image;
      img.alt = ph.heading || p.title;
      img.loading = 'lazy';
      media.appendChild(img);

      var caption = el('div', 'project-row__text');
      if (ph.heading) caption.appendChild(text('h3', null, ph.heading));
      if (ph.text) caption.appendChild(text('p', null, ph.text));

      row.appendChild(media);
      row.appendChild(caption);
      photosWrap.appendChild(row);
    });
    photosSec.appendChild(photosWrap);
    root.appendChild(photosSec);

    var back = el('section', 'section text-center project-back');
    back.appendChild(el('div', null,
      '<a class="btn" href="gallery.html">Back to Gallery</a>'));
    root.appendChild(back);
  }

  function renderNotFound(root) {
    var sec = el('section', 'page-hero');
    var wrap = el('div', 'container');
    wrap.appendChild(text('h1', null, 'Project not found'));
    wrap.appendChild(el('p', 'lede',
      'This project may have been moved or renamed. <a href="gallery.html">Browse the full gallery</a>.'));
    sec.appendChild(wrap);
    root.appendChild(sec);
  }

  /* ---------- Boot ---------- */
  var grid = document.querySelector('[data-projects-grid]');
  var featured = document.querySelector('[data-projects-featured]');
  var page = document.querySelector('[data-project-page]');

  /* Reserve the grid's eventual height BEFORE the tiles render, so the
     content below it does not jump when they land (see .gallery-grid in
     style.css). The embedded snapshot is a plain synchronous script that
     loads ahead of this file, so the project count is usually known right
     now — well before the fetch resolves. Falls back to the CSS default of
     one row when it is not. */
  function reserveRows(el, count) {
    if (!el || !count) return;
    var min = 300, gap = 22.4;             // matches the grid's CSS
    var perRow = Math.max(1, Math.floor((el.clientWidth + gap) / (min + gap)));
    el.style.setProperty('--rows', Math.ceil(count / perRow));
  }

  if (grid || featured) {
    var known = (window.INDIGO_PROJECTS && window.INDIGO_PROJECTS.order || []).length;
    if (known) {
      reserveRows(grid, known);
      if (featured) {
        reserveRows(featured,
          Math.min(known, parseInt(featured.getAttribute('data-projects-featured'), 10) || 3));
      }
    }
    loadAll().then(function (projects) {
      if (!projects.length) return;
      if (grid) renderGrid(grid, projects);
      if (featured) renderFeatured(featured, projects);
    }).catch(function (err) {
      console.warn('[projects] could not load project data:', err.message);
      if (grid) grid.innerHTML = '<p>Our gallery is being updated — please check back soon.</p>';
    });
  }

  if (page) {
    /* A generated page at /projects/<slug>/ declares its own slug; the
       older project.html?p=<slug> URL still carries it in the query
       string and keeps working. */
    var slug = window.INDIGO_PROJECT_SLUG ||
               new URLSearchParams(location.search).get('p');
    if (!slug || /[^a-z0-9-]/.test(slug)) {
      renderNotFound(page);
    } else {
      loadOne(slug).then(function (p) {
        renderProject(page, p);
      }).catch(function () {
        renderNotFound(page);
      });
    }
  }
})();
