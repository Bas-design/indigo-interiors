/* Regenerates projects-data.js — an embedded snapshot of all project.json
   files. The live site reads the JSON directly; the snapshot is only used
   as a fallback so the gallery works when the site is opened straight from
   the file system (file://), where browsers block fetch().

   Run from this folder after adding/editing projects (needs Node.js):
       node rebuild-preview-data.js
   Forgetting to run it does NOT affect the live site. */
'use strict';
var fs = require('fs');
var path = require('path');

var here = __dirname;
var list = JSON.parse(fs.readFileSync(path.join(here, 'projects.json'), 'utf8'));
var out = {};

list.projects.forEach(function (slug) {
  var f = path.join(here, slug, 'project.json');
  try {
    out[slug] = JSON.parse(fs.readFileSync(f, 'utf8'));
    console.log('ok:      ' + slug);
  } catch (e) {
    console.warn('SKIPPED: ' + slug + ' — ' + e.message);
  }
});

var js = '/* AUTO-GENERATED by rebuild-preview-data.js — do not edit by hand.\n' +
  '   Snapshot of the project JSON files, used only when fetch() is\n' +
  '   unavailable (viewing the site from the file system). */\n' +
  'window.INDIGO_PROJECTS = ' + JSON.stringify({ order: list.projects, data: out }, null, 2) + ';\n';

fs.writeFileSync(path.join(here, 'projects-data.js'), js);
console.log('\nwrote projects-data.js (' + list.projects.length + ' projects)');
